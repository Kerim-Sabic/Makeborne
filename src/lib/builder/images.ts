import "server-only";
import { createHash } from "node:crypto";
import OpenAI from "openai";
import sharp from "sharp";
import type { SupabaseClient } from "@supabase/supabase-js";
import type { ImageClientLike } from "../ai/image-call";
import { imagePrice, type ImageSize } from "../ai/prices";
import type { SourceAsset } from "./files";

export type ImageConfiguration = { model: string; issue: null } | { model: null; issue: string };
/**
 * Image generation is opt-in. It needs OPENAI_API_KEY and an explicitly set
 * MAKEBORNE_IMAGE_MODEL with a current, bounded price card. There is no default
 * model, so a provider retirement or a new release never changes spend silently.
 * Without a usable configuration images are off and runs continue with
 * typography, CSS and SVG; a set key with an unusable model is logged.
 */
export function imageConfiguration(now = Date.now()): ImageConfiguration {
  if (!process.env.OPENAI_API_KEY) return { model: null, issue: "OPENAI_API_KEY is not set" };
  const model = process.env.MAKEBORNE_IMAGE_MODEL?.trim();
  if (!model) return { model: null, issue: "MAKEBORNE_IMAGE_MODEL is not set" };
  try {
    imagePrice(model, now);
  } catch (error) {
    const issue = `MAKEBORNE_IMAGE_MODEL ${model} cannot be used: ${error instanceof Error ? error.message : String(error)}`;
    console.warn(`Image generation is off. ${issue}`);
    return { model: null, issue };
  }
  return { model, issue: null };
}
export const IMAGE_SIZES: Record<ImageAspect, ImageSize> = { landscape: "1536x1024", portrait: "1024x1536", square: "1024x1024" };
export type ImageAspect = "landscape" | "portrait" | "square";

/** OpenAI client with no hidden retries; each attempt is budgeted by the caller. */
export function openaiImageClient(): ImageClientLike {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) throw new Error("Image generation is not connected.");
  return new OpenAI({ apiKey, maxRetries: 0, timeout: 180_000 }) as unknown as ImageClientLike;
}

/** Deterministic asset id bound to workspace, project and exact bytes (same scheme as uploads). */
export function assetId(workspaceId: string, projectId: string, sha256: string) {
  const digest = createHash("sha256").update(`${workspaceId}:${projectId}:${sha256}`).digest("hex");
  return `${digest.slice(0, 8)}-${digest.slice(8, 12)}-5${digest.slice(13, 16)}-a${digest.slice(17, 20)}-${digest.slice(20, 32)}`;
}

/** Store original bytes as a registered project asset through the caller's
 * RLS-bound client, so the existing source-asset verifier accepts it. */
export async function storeProjectImage(client: SupabaseClient, scope: { workspaceId: string; projectId: string }, input: Buffer, provenance: Record<string, unknown>) {
  const bytes = await sharp(input).rotate().webp({ quality: 84 }).toBuffer();
  const meta = await sharp(bytes).metadata();
  if (!meta.width || !meta.height) throw new Error("Generated image could not be decoded.");
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const id = assetId(scope.workspaceId, scope.projectId, sha256);
  const objectPath = `${scope.workspaceId}/${scope.projectId}/artwork/${id}.webp`;
  const existing = await client.from("assets").select("id").eq("workspace_id", scope.workspaceId).eq("id", id).maybeSingle();
  if (existing.error) throw new Error("Asset registry unavailable.");
  if (!existing.data) {
    const uploaded = await client.storage.from("project-assets").upload(objectPath, bytes, { contentType: "image/webp", upsert: false, cacheControl: "0" });
    if (uploaded.error && !/exists|duplicate/i.test(uploaded.error.message)) throw new Error("Image storage failed.");
    const inserted = await client.from("assets").insert({ id, workspace_id: scope.workspaceId, project_id: scope.projectId, object_path: objectPath,
      content_type: "image/webp", sha256, provenance: { ...provenance, byteLength: bytes.length, width: meta.width, height: meta.height } });
    if (inserted.error && inserted.error.code !== "23505") throw new Error("Image registration failed.");
  }
  return { id, sha256, bytes: bytes.length, width: meta.width, height: meta.height };
}

/** Registers generated bytes as a project image whose public URL is `/images/<name>.webp`. */
export async function storeGeneratedImage(client: SupabaseClient, scope: { workspaceId: string; projectId: string }, request: { name: string; prompt: string; model: string }, bytes: Buffer): Promise<SourceAsset & { url: string }> {
  const stored = await storeProjectImage(client, scope, bytes, { kind: "generated", model: request.model, prompt: request.prompt.slice(0, 2000) });
  const path = `public/images/${request.name}.webp`;
  return { id: stored.id, path, sha256: stored.sha256, bytes: stored.bytes, mediaType: "image/webp", url: `/images/${request.name}.webp` };
}
