-- Review link view tracking: the owner learns that a shared review link was
-- opened, for how long, and which slides or pages held attention.
-- Additive only: one new table and one new public function. Existing review
-- tables and functions are unchanged.
--
-- Stored per view session (a random id the browser keeps for one tab):
-- start and last-seen times, bounded active seconds, open count, a coarse
-- device class, and seconds per slide/page/section (at most 200 entries).
-- Never stored: IP address, user agent string, cookies, names or emails.
-- ROLLOUT: rehearse with supabase/check-review-link-views.sql, then apply.
-- The app treats a missing table/function as "not set up yet" and the review
-- page never depends on it. RECOVERY: drop the function, then the table; no
-- other object references them.
begin;

create table public.client_review_views (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null,
  link_id uuid not null,
  -- Random per-tab id generated by the viewer's browser; not a cookie.
  session_id uuid not null,
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  -- Visible-tab seconds. Each heartbeat adds at most 60; a session at most 4 h.
  active_seconds integer not null default 0 check(active_seconds between 0 and 14400),
  -- Page loads within the same tab session.
  opens integer not null default 1 check(opens between 1 and 1000),
  device text not null check(device in ('phone','tablet','desktop')),
  -- {"slide:5":{"s":120,"l":"Slide 6 · Pricing"}}; at most 200 keys (enforced by the writer).
  pages jsonb not null default '{}'::jsonb check(jsonb_typeof(pages)='object' and octet_length(pages::text)<=100000),
  unique(link_id,session_id),
  check(last_seen_at>=started_at),
  foreign key(link_id,workspace_id) references public.client_review_links(id,workspace_id) on delete cascade
);
create index client_review_views_link on public.client_review_views(link_id,started_at desc);
create index client_review_views_workspace on public.client_review_views(workspace_id,started_at desc);

alter table public.client_review_views enable row level security;
revoke all on public.client_review_views from public,anon,authenticated;
-- Members read their workspace's rows (never the browser session id); nobody writes directly.
grant select(id,workspace_id,link_id,started_at,last_seen_at,active_seconds,opens,device,pages)
  on public.client_review_views to authenticated;
create policy client_review_views_read on public.client_review_views for select to authenticated using(makeborne_private.can_read(workspace_id));
grant select,insert,update,delete on public.client_review_views to service_role;

-- Public heartbeat: token in, hash compared through the shared live-link helper.
-- p_slices: [{"ref":"slide:5","label":"Slide 6 · Pricing","seconds":12}] (at most 20, each 0–60 s).
create function public.makeborne_record_client_review_view(p_token text,p_session uuid,p_device text,p_open boolean,p_slices jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare r public.client_review_links%rowtype; s public.client_review_views%rowtype; item jsonb;
  v_inserted boolean := false; v_budget integer; v_seconds integer; v_total integer := 0;
  v_ref text; v_label text; v_pages jsonb; v_number numeric;
begin
  if p_session is null or p_open is null or p_device is null or p_device not in ('phone','tablet','desktop')
    or p_slices is null or jsonb_typeof(p_slices)<>'array' or jsonb_array_length(p_slices)>20 then
    raise exception 'Invalid view' using errcode='22023';
  end if;
  for item in select value from jsonb_array_elements(p_slices) loop
    if jsonb_typeof(item)<>'object' then raise exception 'Invalid view' using errcode='22023'; end if;
    v_number := case when jsonb_typeof(item->'seconds')='number' then (item->>'seconds')::numeric end;
    if (item-array['ref','label','seconds'])<>'{}'::jsonb
      or jsonb_typeof(item->'ref') is distinct from 'string' or (item->>'ref') !~ '^[A-Za-z0-9:_.-]{1,100}$'
      or (item ? 'label' and (jsonb_typeof(item->'label') is distinct from 'string' or length(item->>'label')>400))
      or v_number is null or v_number<0 or v_number>60 or v_number<>pg_catalog.trunc(v_number) then
      raise exception 'Invalid view' using errcode='22023';
    end if;
  end loop;
  select * into r from makeborne_private.client_review_live_link(p_token,false);
  -- The owner or a member previewing their own link is not counted.
  if (select auth.uid()) is not null and makeborne_private.can_read(r.workspace_id) then
    return jsonb_build_object('recorded',false,'reason','member');
  end if;
  select * into s from public.client_review_views where link_id=r.id and session_id=p_session for update;
  if not found then
    -- Serialise new sessions per link so the daily limits are exact.
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('makeborne_client_review_views:'||r.id::text,0));
    select * into s from public.client_review_views where link_id=r.id and session_id=p_session for update;
  end if;
  if not found then
    if (select count(*) from public.client_review_views where link_id=r.id and started_at>now()-interval '1 day')>=200
      or (select count(*) from public.client_review_views where workspace_id=r.workspace_id and started_at>now()-interval '1 day')>=5000 then
      raise exception 'Too many views. Please wait.' using errcode='MB429';
    end if;
    insert into public.client_review_views(workspace_id,link_id,session_id,device)
    values(r.workspace_id,r.id,p_session,p_device) returning * into s;
    v_inserted := true;
    v_budget := 60;
  else
    -- At most one heartbeat per second per session.
    if now()-s.last_seen_at<interval '1 second' then
      return jsonb_build_object('recorded',false,'reason','throttled');
    end if;
    -- Never more time than actually passed (plus a little slack), never more than 60 s.
    v_budget := least(60,pg_catalog.ceil(extract(epoch from now()-s.last_seen_at))::integer+5);
  end if;
  v_budget := greatest(0,least(v_budget,14400-s.active_seconds));
  v_pages := s.pages;
  for item in select value from jsonb_array_elements(p_slices) loop
    v_seconds := least((item->>'seconds')::integer,v_budget);
    v_ref := item->>'ref';
    v_label := pg_catalog.left(makeborne_private.client_review_text(item->>'label'),80);
    if v_pages ? v_ref then
      v_pages := jsonb_set(v_pages,array[v_ref],jsonb_build_object(
        's',least(14400,coalesce((v_pages->v_ref->>'s')::integer,0)+v_seconds),
        'l',case when v_label<>'' then v_label else coalesce(v_pages->v_ref->>'l','') end));
    elsif (select count(*) from jsonb_object_keys(v_pages))<200 then
      v_pages := v_pages||jsonb_build_object(v_ref,jsonb_build_object('s',v_seconds,'l',v_label));
    end if;
    v_total := v_total+v_seconds;
    v_budget := v_budget-v_seconds;
  end loop;
  update public.client_review_views set
    active_seconds=least(14400,active_seconds+v_total),
    pages=v_pages,
    last_seen_at=greatest(last_seen_at,now()),
    opens=case when p_open and not v_inserted then least(opens+1,1000) else opens end
  where id=s.id returning * into s;
  return jsonb_build_object('recorded',true,'activeSeconds',s.active_seconds);
end $$;
revoke all on function public.makeborne_record_client_review_view(text,uuid,text,boolean,jsonb) from public,anon,authenticated,service_role;
grant execute on function public.makeborne_record_client_review_view(text,uuid,text,boolean,jsonb) to anon,authenticated,service_role;
commit;
